export function courseFlat(): { step: PathStep; lesson: Lesson }[] {
  const out: { step: PathStep; lesson: Lesson }[] = [];
  PATH.forEach((step) =>
    step.lessons.forEach((lesson) => out.push({ step, lesson }))
  );
  return out;
}

export function courseStats(doneLessons: readonly string[] = []) {
  const flat = courseFlat();
  let done = 0;
  flat.forEach((f) => {
    if (doneLessons.includes(f.lesson.id)) done++;
  });
  return {
    done,
    total: flat.length,
    pct: flat.length ? Math.round((done / flat.length) * 100) : 0,
  };
}

